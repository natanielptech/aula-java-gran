package br.com.exemplo.tarefas;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

public class TarefaDAO {
    public TarefaDAO() throws SQLException {
        String sql = """
                CREATE TABLE IF NOT EXISTS tarefas (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    descricao VARCHAR(255) NOT NULL,
                    concluida BOOLEAN NOT NULL DEFAULT FALSE
                )
                """;

        try (Connection conexao = Conexao.obterConexao();
             Statement comando = conexao.createStatement()) {
            comando.execute(sql);
        }
    }

    public Tarefa criar(String descricao) throws SQLException {
        String sql = "INSERT INTO tarefas (descricao) VALUES (?)";

        try (Connection conexao = Conexao.obterConexao();
             PreparedStatement comando = conexao.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            comando.setString(1, descricao);
            comando.executeUpdate();

            try (ResultSet chaves = comando.getGeneratedKeys()) {
                if (chaves.next()) {
                    return new Tarefa(chaves.getInt(1), descricao, false);
                }
            }
        }

        throw new SQLException("Não foi possível obter o ID da tarefa criada.");
    }

    public List<Tarefa> listar() throws SQLException {
        String sql = "SELECT id, descricao, concluida FROM tarefas ORDER BY id";
        List<Tarefa> tarefas = new ArrayList<>();

        try (Connection conexao = Conexao.obterConexao();
             Statement comando = conexao.createStatement();
             ResultSet resultados = comando.executeQuery(sql)) {
            while (resultados.next()) {
                tarefas.add(new Tarefa(
                        resultados.getInt("id"),
                        resultados.getString("descricao"),
                        resultados.getBoolean("concluida")));
            }
        }

        return tarefas;
    }

    public boolean atualizar(int id, String descricao, boolean concluida) throws SQLException {
        String sql = "UPDATE tarefas SET descricao = ?, concluida = ? WHERE id = ?";

        try (Connection conexao = Conexao.obterConexao();
             PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setString(1, descricao);
            comando.setBoolean(2, concluida);
            comando.setInt(3, id);
            return comando.executeUpdate() > 0;
        }
    }

    public boolean excluir(int id) throws SQLException {
        String sql = "DELETE FROM tarefas WHERE id = ?";

        try (Connection conexao = Conexao.obterConexao();
             PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setInt(1, id);
            return comando.executeUpdate() > 0;
        }
    }
}
